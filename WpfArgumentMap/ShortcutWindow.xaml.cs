    public ShortcutWindow()
    {
        InitializeComponent();
        UpdateResults();
        Loaded += (_, _) => SearchBox.Focus();
    }

    private void Search_TextChanged(object sender, TextChangedEventArgs e)
    {
        if (ShortcutGroups is not null) UpdateResults();
    }

    private void UpdateResults()
    {
        var query = SearchBox.Text.Trim();
        var matches = Shortcuts.Where(s => $"{s.Group} {s.Keys} {s.Action} {s.Detail}"
            .Contains(query, StringComparison.OrdinalIgnoreCase)).ToArray();
        ShortcutGroups.ItemsSource = matches.GroupBy(s => s.Group).Select(g => new ShortcutGroup(g.Key, g.ToArray())).ToArray();
        EmptyResults.Visibility = matches.Length == 0 ? Visibility.Visible : Visibility.Collapsed;
        ResultCount.Text = $"{matches.Length} 项操作 · 节点为整数，交点允许 0.5";
        ShortcutScroll.ScrollToTop();
    }

    private void Close_Click(object sender, RoutedEventArgs e) => Close();
    private void Window_PreviewKeyDown(object sender, KeyEventArgs e)
    {
        if (e.Key != Key.Escape) return;
        Close();
        e.Handled = true;
    }
