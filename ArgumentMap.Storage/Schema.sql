    Id INT NOT NULL PRIMARY KEY,
    SchemaVersion INT NOT NULL,
    CONSTRAINT AM9_CK_Metadata CHECK (Id = 1)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='地图架构版本及事务锁';

CREATE TABLE IF NOT EXISTS `Lines` (
    LineCode VARCHAR(10) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
    Owner VARCHAR(255) NOT NULL,
    IsLocked BOOLEAN NOT NULL DEFAULT FALSE,
    IsChanged INT NOT NULL DEFAULT 0,
    Version BIGINT NOT NULL DEFAULT 0,
    RoadName VARCHAR(32) NOT NULL DEFAULT '',
    RoadDetail VARCHAR(255) NOT NULL DEFAULT '',
    Speed INT NOT NULL DEFAULT 100,
    PassInDirection SMALLINT NOT NULL DEFAULT 1,
    PassInOpposeDirection SMALLINT NOT NULL DEFAULT 0,
    UpdatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT AM9_CK_Lines CHECK (REGEXP_LIKE(LineCode, '^[A-Z]{10}$', 'c') AND CHAR_LENGTH(TRIM(Owner)) > 0 AND IsLocked IN (0, 1) AND Version >= 0),
    CONSTRAINT AM9_CK_Lines_Speed CHECK (Speed BETWEEN 5 AND 500),
    CONSTRAINT AM9_CK_Lines_PassDirection CHECK (PassInDirection=1 AND PassInOpposeDirection IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='逻辑线路';

CREATE TABLE IF NOT EXISTS LineNodes (
    LineCode VARCHAR(10) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    NodeOrder INT NOT NULL,
    X INT NOT NULL,
    Y INT NOT NULL,
    IsChanged INT NOT NULL DEFAULT 0,
    PRIMARY KEY (LineCode, NodeOrder),
    UNIQUE KEY UQ_NodeCoordinate (X, Y),
    CONSTRAINT AM9_FK_Node_Line FOREIGN KEY (LineCode) REFERENCES `Lines`(LineCode) ON DELETE CASCADE,
    CONSTRAINT AM9_CK_Nodes CHECK (NodeOrder >= 0 AND X BETWEEN 0 AND 500000 AND Y BETWEEN 0 AND 500000)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='整数节点及线路内顺序';

CREATE TABLE IF NOT EXISTS Crosses (
    RoadCode1 VARCHAR(10) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    RoadCode2 VARCHAR(10) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    X INT NOT NULL,
    Y INT NOT NULL,
    RoadOrder1 INT NOT NULL,
    RoadOrder2 INT NOT NULL,
    Percent1 DECIMAL(20,18) NOT NULL DEFAULT 0,
    Percent2 DECIMAL(20,18) NOT NULL DEFAULT 0,
    RoadVersion1 BIGINT NOT NULL,
    RoadVersion2 BIGINT NOT NULL,
    CrossState INT NOT NULL DEFAULT 0,
    Version BIGINT NOT NULL DEFAULT 0,
    IsChanged INT NOT NULL DEFAULT 0,
    UpdatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    PRIMARY KEY (RoadCode1, RoadCode2, X, Y),
    KEY IX_Cross_Line1Segment (RoadCode1, RoadOrder1),
    KEY IX_Cross_Line2Segment (RoadCode2, RoadOrder2),
    KEY IX_Cross_Line2 (RoadCode2),
    CONSTRAINT AM9_FK_Cross_Line1 FOREIGN KEY (RoadCode1) REFERENCES `Lines`(LineCode) ON DELETE CASCADE,
    CONSTRAINT AM9_FK_Cross_Line2 FOREIGN KEY (RoadCode2) REFERENCES `Lines`(LineCode) ON DELETE CASCADE,
    CONSTRAINT AM9_CK_Cross_Position CHECK (Percent1 BETWEEN 0 AND 1 AND Percent2 BETWEEN 0 AND 1),
    CONSTRAINT CK_Cross_IntegerCoordinates CHECK (X BETWEEN 0 AND 500000 AND Y BETWEEN 0 AND 500000 AND X=FLOOR(X) AND Y=FLOOR(Y)),
    CONSTRAINT AM9_CK_Cross CHECK (REGEXP_LIKE(RoadCode1, '^[A-Z]{10}$', 'c') AND REGEXP_LIKE(RoadCode2, '^[A-Z]{10}$', 'c') AND RoadCode1 > RoadCode2 AND X BETWEEN 0 AND 500000 AND Y BETWEEN 0 AND 500000
        AND X * 2 = FLOOR(X * 2) AND Y * 2 = FLOOR(Y * 2)
        AND RoadOrder1 >= 0 AND RoadOrder2 >= 0 AND RoadVersion1 >= 0 AND RoadVersion2 >= 0 AND CrossState IN (-1, 0, 1, 2, 3) AND Version >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='整数交点及通行关系，按线路对及整数坐标识别';

CREATE TABLE IF NOT EXISTS LogicalNodes (
    Code VARCHAR(10) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
    Owner VARCHAR(255) NOT NULL,
    Version BIGINT NOT NULL DEFAULT 0,
    X DECIMAL(34,28) NOT NULL,
    Y DECIMAL(34,28) NOT NULL,
    SideLength INT NOT NULL,
    StartSlot TINYINT GENERATED ALWAYS AS (CASE WHEN SideLength=18 THEN 1 ELSE NULL END) STORED,
    UNIQUE KEY UQ_LN_Start (StartSlot),
    `Value` VARCHAR(32) NOT NULL DEFAULT '',
    Value12Key VARBINARY(128) GENERATED ALWAYS AS (CASE WHEN SideLength=12 THEN CONVERT(`Value` USING binary) ELSE NULL END) STORED,
    UNIQUE KEY UQ_LN_Value12 (Value12Key),
    Info VARCHAR(255) NOT NULL DEFAULT '',
    LogicLanguage VARCHAR(255) NOT NULL DEFAULT '' COMMENT '逻辑语言／命题表达式',
    Logic6Key VARBINARY(1020) GENERATED ALWAYS AS (CASE WHEN SideLength=6 THEN CONVERT(LogicLanguage USING binary) ELSE NULL END) STORED,
    UNIQUE KEY UQ_LN_Logic6 (Logic6Key),
    CONSTRAINT CK_LN_Logic6Required CHECK (SideLength<>6 OR REGEXP_LIKE(LogicLanguage,'[^[:space:]]','c')),
    CONSTRAINT CK_LN_Logic12Required CHECK (SideLength<>12 OR REGEXP_LIKE(LogicLanguage,'[^[:space:]]','c')),
    CONSTRAINT CK_LN_BranchValue CHECK (SideLength<>4 OR CONVERT(`Value` USING binary) IN (_binary'True',_binary'False')),
    CONSTRAINT CK_LN_RelationValue CHECK (SideLength<>8 OR CONVERT(`Value` USING binary) IN (X'3D',X'E28692',X'E28694',X'E28A87',X'E28A8B',X'E28A86',X'E28A8A',X'C2AC')),
    CONSTRAINT CK_LN_RelationLogic CHECK (SideLength<>8 OR CONVERT(LogicLanguage USING binary)=CASE WHEN CONVERT(`Value` USING binary)=X'C2AC' THEN X'C2AC283F29' ELSE CONVERT(`Value` USING binary) END),
    UpdatedAt DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    CONSTRAINT CK_LN_Value12Upper CHECK (SideLength<>12 OR CONVERT(`Value` USING binary)=CONVERT(UPPER(`Value`) USING binary)),
    CONSTRAINT CK_LN_InstanceValue CHECK (SideLength<>10 OR (REGEXP_LIKE(`Value`,'[^[:space:]]','c') AND CONVERT(`Value` USING binary)=CONVERT(LOWER(`Value`) USING binary))),
    CONSTRAINT CK_LN_InstanceLogic CHECK (SideLength<>10 OR CONVERT(LogicLanguage USING binary)=CONVERT(CONCAT(`Value`,' ∈ ',UPPER(`Value`)) USING binary)),
    CONSTRAINT CK_LN_CenterHalf CHECK (MOD(X,1)=0.5 AND MOD(Y,1)=0.5),
    CONSTRAINT CK_LN_V14 CHECK (REGEXP_LIKE(Code, '^[A-Z]{10}$', 'c') AND CHAR_LENGTH(TRIM(Owner))>0 AND Version>=0
        AND MOD(X,1)=0.5 AND MOD(Y,1)=0.5 AND SideLength IN (4,6,8,10,12,18)
        AND X-SideLength/2>=0 AND Y-SideLength/2>=0 AND X+SideLength/2<=500000 AND Y+SideLength/2<=500000)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci COMMENT='LN 节点主表，位置独立保存为一对多';

